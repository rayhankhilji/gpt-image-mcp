/**
 * Prompt presets for ChatGPT's image model.
 *
 * Built on OpenAI's GPT Image prompting guide: write in a consistent order
 * (intended use → scene → subject → key details → constraints), be concrete about medium,
 * materials and light, quote exact text, state what must NOT appear, and keep one clear job per image.
 *
 * A preset fills the structure; the agent's prompt supplies the subject. Styles are modifiers that
 * combine with any preset (presets × styles = hundreds of distinct outcomes).
 */

